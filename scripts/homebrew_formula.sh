#!/bin/sh
# Print the Homebrew formula for a soothsay release.
#
#   scripts/homebrew_formula.sh v0.2.0 dist/SHA256SUMS > Formula/soothsay.rb
#
# The formula installs the prebuilt, attested release binaries (no Rust needed)
# and pins each one to its hash from the release's SHA256SUMS. The release
# workflow runs this and pushes the result to rijuld/homebrew-tap.
set -eu

if [ "$#" -ne 2 ]; then
    echo "usage: $0 TAG SHA256SUMS" >&2
    exit 2
fi
tag=$1
sums=$2
version=${tag#v}
base="https://github.com/rijuld/soothsay/releases/download/${tag}"

sha() {
    file="soothsay-${tag}-$1.tar.gz"
    h=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
    case "$h" in
        [0-9a-f]*) ;;
        *) echo "no hash for $file in $sums" >&2; exit 1 ;;
    esac
    if [ "${#h}" -ne 64 ]; then
        echo "bad hash for $file in $sums" >&2
        exit 1
    fi
    echo "$h"
}

mac_arm=$(sha aarch64-apple-darwin)
mac_x86=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-musl)
linux_x86=$(sha x86_64-unknown-linux-musl)

cat <<EOF
# Generated by scripts/homebrew_formula.sh in rijuld/soothsay. Don't edit by hand:
# the release workflow overwrites this file on every release.
class Soothsay < Formula
  desc "Explains what a shell install script will do to your machine, before it does it"
  homepage "https://github.com/rijuld/soothsay"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/soothsay-${tag}-aarch64-apple-darwin.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${base}/soothsay-${tag}-x86_64-apple-darwin.tar.gz"
      sha256 "${mac_x86}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/soothsay-${tag}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/soothsay-${tag}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${linux_x86}"
    end
  end

  def install
    bin.install "soothsay"
  end

  test do
    (testpath/"install.sh").write "echo hello\n"
    assert_match "soothsay hook", shell_output("#{bin}/soothsay --help")
    system bin/"soothsay", testpath/"install.sh"
  end
end
EOF
